// Quote a state/symbol as a C++ string literal (escaping backslash and quote).
QString cppLit(const QString& s)
{
    QString out = QStringLiteral("\"");
    for (const QChar c : s) {
        if (c == QLatin1Char('\\') || c == QLatin1Char('"'))
            out += QLatin1Char('\\');
        out += c;
    }
    out += QLatin1Char('"');
    return out;
}

// Neutralize "*/" so free-form action text is safe inside a C++ /* ... */ comment.
QString commentSafe(const QString& s)
{
    QString v = s;
    v.replace(QStringLiteral("*/"), QStringLiteral("* /"));
    return v;
}

// Quote an identifier/label as a DOT double-quoted string.
QString dotQuote(const QString& s)
{
    QString v = s;
    v.replace(QLatin1Char('\\'), QStringLiteral("\\\\"))
        .replace(QLatin1Char('"'), QStringLiteral("\\\""));
    return QLatin1Char('"') + v + QLatin1Char('"');
}

// Decode a C++ string-literal body (the chars between the quotes).
QString unescapeCppLit(const QString& s)
{
    QString out;
    out.reserve(s.size());
    for (int i = 0; i < s.size(); ++i) {
        const QChar c = s[i];
        if (c == QLatin1Char('\\') && i + 1 < s.size()) {
            const QChar n = s[++i];
            switch (n.unicode()) {
            case 'n':
                out += QLatin1Char('\n');
                break;
            case 't':
                out += QLatin1Char('\t');
                break;
            default:
                out += n;
                break;  // covers \" and \\ and anything else
            }
        } else {
            out += c;
        }
    }
    return out;
}

// Strip DOT quotes/escapes from an id or attribute value.
QString dotUnquote(QString s)
{
    s = s.trimmed();
    if (s.size() >= 2 && s.startsWith(QLatin1Char('"')) && s.endsWith(QLatin1Char('"')))
        return unescapeCppLit(s.mid(1, s.size() - 2));
    return s;
}

