QString exportCpp(const fsmdef::FsmDefinition& def)
{
    QString code;
    QTextStream ts(&code);
    ts << "#include \"fsm.hpp\"\n";
    ts << "#include <string>\n\n";
    ts << "// Generated by fsm_visualizer.\n";
    ts << "// A deterministic machine over std::string states and symbols.\n";
    ts << "inline fsm::dfa<std::string, std::string> make_machine() {\n";
    ts << "  fsm::dfa<std::string, std::string> m;\n";
    if (!def.initial.isEmpty())
        ts << "  m.start(" << cppLit(def.initial) << ");\n";
    for (const QString& a : def.accept)
        ts << "  m.accept(" << cppLit(a) << ");\n";
    if (!def.tr.empty())
        ts << "\n";
    for (const fsmdef::Transition& t : def.tr)
        ts << "  m.on(" << cppLit(QString::fromStdString(t.from)) << ", "
           << cppLit(QString::fromStdString(t.sym)) << ", " << cppLit(QString::fromStdString(t.to))
           << ");\n";
    // Per-state entry/exit actions. The visualizer holds free-form text (not code),
    // so each action body is emitted as a comment stub for you to fill in.
    if (!def.entry.isEmpty() || !def.exit.isEmpty())
        ts << "\n";
    for (auto it = def.entry.cbegin(); it != def.entry.cend(); ++it)
        ts << "  m.on_entry(" << cppLit(it.key()) << ", []{ /* " << commentSafe(it.value())
           << " */ });\n";
    for (auto it = def.exit.cbegin(); it != def.exit.cend(); ++it)
        ts << "  m.on_exit(" << cppLit(it.key()) << ", []{ /* " << commentSafe(it.value())
           << " */ });\n";
    // The visualizer runs with ::ignore so stray input is harmless; switch to
    // ::halt for strict DFA / language-recognition semantics.
    ts << "\n  m.undefined(fsm::on_undefined::ignore);\n";
    ts << "  return m;\n";
    ts << "}\n";
    return code;
}

QString exportDot(const fsmdef::FsmDefinition& def)
{
    QString out;
    QTextStream ts(&out);
    ts << "digraph fsm {\n";
    ts << "  rankdir=LR;\n";
    ts << "  node [fontname=\"sans-serif\"];\n";
    ts << "  edge [fontname=\"sans-serif\"];\n";
    // Declare every state so isolated ones still appear; accepting = doublecircle.
    for (const QString& s : def.states)
        ts << "  " << dotQuote(s)
           << " [shape=" << (def.accept.contains(s) ? "doublecircle" : "circle") << "];\n";
    // Initial state: an arrow from a hidden point node.
    if (!def.initial.isEmpty()) {
        ts << "  __start [shape=point width=0.12];\n";
        ts << "  __start -> " << dotQuote(def.initial) << ";\n";
    }
    for (const fsmdef::Transition& t : def.tr)
        ts << "  " << dotQuote(QString::fromStdString(t.from)) << " -> "
           << dotQuote(QString::fromStdString(t.to))
           << " [label=" << dotQuote(QString::fromStdString(t.sym)) << "];\n";
    ts << "}\n";
    return out;
}

QVariantMap importCpp(const QString& code)
{
    auto addUnique = [](QStringList& list, const QString& v) {
        if (!v.isEmpty() && !list.contains(v))
            list << v;
    };
    QStringList states, symbols, accept, trLines;
    QString initial;

    // on("from", "symbol", "to")  — any receiver/variable, flexible whitespace.
    static const QRegularExpression onRe(QStringLiteral(
        R"RX(\.\s*on\s*\(\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*\))RX"));
    for (auto it = onRe.globalMatch(code); it.hasNext();) {
        const QRegularExpressionMatch m = it.next();
        const QString f = unescapeCppLit(m.captured(1));
        const QString s = unescapeCppLit(m.captured(2));
        const QString t = unescapeCppLit(m.captured(3));
        addUnique(states, f);
        addUnique(states, t);
        addUnique(symbols, s);
        trLines << QStringLiteral("%1, %2, %3").arg(f, s, t);
    }
    // start("state")
    static const QRegularExpression startRe(
        QStringLiteral(R"RX(\.\s*start\s*\(\s*"((?:[^"\\]|\\.)*)"\s*\))RX"));
    const QRegularExpressionMatch sm = startRe.match(code);
    if (sm.hasMatch()) {
        initial = unescapeCppLit(sm.captured(1));
        addUnique(states, initial);
    }
    // accept("state")
    static const QRegularExpression accRe(
        QStringLiteral(R"RX(\.\s*accept\s*\(\s*"((?:[^"\\]|\\.)*)"\s*\))RX"));
    for (auto it = accRe.globalMatch(code); it.hasNext();) {
        const QString a = unescapeCppLit(it.next().captured(1));
        addUnique(accept, a);
        addUnique(states, a);
    }

    QVariantMap out;
    if (trLines.isEmpty() && initial.isEmpty() && accept.isEmpty())
        return out;  // nothing recognisable
    out[QStringLiteral("symbols")] = symbols.join(QStringLiteral(", "));
    out[QStringLiteral("states")] = states.join(QStringLiteral(", "));
    out[QStringLiteral("transitions")] = trLines.join(QLatin1Char('\n'));
    out[QStringLiteral("initial")] = initial;
    out[QStringLiteral("accept")] = accept.join(QStringLiteral(", "));
    return out;
}

QVariantMap importDot(const QString& code)
{
    auto addUnique = [](QStringList& list, const QString& v) {
        if (!v.isEmpty() && !list.contains(v))
            list << v;
    };
    QStringList states, symbols, accept, trLines, startMarkers;
    QString initial;

    // Node statement: ID [attrs]  (also matches an edge target that carries attrs,
    // which is harmless — those have a label, not a shape).
    static const QRegularExpression nodeRe(
        QStringLiteral(R"RX(("(?:[^"\\]|\\.)*"|[A-Za-z_][A-Za-z0-9_]*)\s*\[([^\]]*)\])RX"));
    static const QRegularExpression dcRe(QStringLiteral(R"(shape\s*=\s*doublecircle)"));
    static const QRegularExpression ptRe(QStringLiteral(R"(shape\s*=\s*(?:point|none))"));
    // Pass 1: node shapes + declared states (in file order), minus start markers.
    for (auto it = nodeRe.globalMatch(code); it.hasNext();) {
        const QRegularExpressionMatch m = it.next();
        const QString id = dotUnquote(m.captured(1));
        const QString attrs = m.captured(2);
        if (ptRe.match(attrs).hasMatch()) {
            addUnique(startMarkers, id);
            continue;
        }
        if (dcRe.match(attrs).hasMatch())
            addUnique(accept, id);
        addUnique(states, id);
    }
    // Pass 2: edges. ID -> ID [attrs]?
    static const QRegularExpression edgeRe(QStringLiteral(
        R"RX(("(?:[^"\\]|\\.)*"|[A-Za-z_][A-Za-z0-9_]*)\s*->\s*("(?:[^"\\]|\\.)*"|[A-Za-z_][A-Za-z0-9_]*)\s*(?:\[([^\]]*)\])?)RX"));
    static const QRegularExpression labelRe(
        QStringLiteral(R"RX(label\s*=\s*("(?:[^"\\]|\\.)*"|[^,\]\s]+))RX"));
    for (auto it = edgeRe.globalMatch(code); it.hasNext();) {
        const QRegularExpressionMatch m = it.next();
        const QString from = dotUnquote(m.captured(1)), to = dotUnquote(m.captured(2));
        if (startMarkers.contains(from)) {  // marker -> initial state
            if (initial.isEmpty())
                initial = to;
            addUnique(states, to);
            continue;
        }
        addUnique(states, from);
        addUnique(states, to);
        const QRegularExpressionMatch lm = labelRe.match(m.captured(3));
        if (lm.hasMatch()) {
            const QString label = dotUnquote(lm.captured(1));
            if (!label.isEmpty()) {
                addUnique(symbols, label);
                trLines << QStringLiteral("%1, %2, %3").arg(from, label, to);
            }
        }
    }

    QVariantMap out;
    if (trLines.isEmpty() && initial.isEmpty() && accept.isEmpty() && states.isEmpty())
        return out;
    out[QStringLiteral("symbols")] = symbols.join(QStringLiteral(", "));
    out[QStringLiteral("states")] = states.join(QStringLiteral(", "));
    out[QStringLiteral("transitions")] = trLines.join(QLatin1Char('\n'));
    out[QStringLiteral("initial")] = initial;
    out[QStringLiteral("accept")] = accept.join(QStringLiteral(", "));
    return out;
}

